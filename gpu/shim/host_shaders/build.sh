#!/usr/bin/env bash
# Regenerates the embedded SPIR-V (host_shaders.h) from these shaders: needs glslc (MSYS2
# CLANG64: mingw-w64-clang-x86_64-shaderc).
set -euo pipefail
cd -- "$(dirname -- "$0")"
out=../bbport_native_vk_host_shaders.h
{
    echo '// Generated by host_shaders/build.sh from host_shaders/*. Do not edit.'
    echo '#pragma once'
    echo '#include <cstdint>'
    echo 'namespace BbNativeVk::HostShaders {'
    for f in fullscreen.vert depth_to_color.frag copy_color.frag; do
        name=$(echo "$f" | tr '.' '_')
        echo "inline constexpr std::uint32_t $name[] = {"
        glslc -O --target-env=vulkan1.2 -mfmt=num -o - "$f"
        echo '};'
    done
    echo '} // namespace BbNativeVk::HostShaders'
} > "$out"
