"""Local auth-key patch: trust the LOCAL RyuNET server's signing key when testing on this PC.

The bundled CrashTeamRacingOnline.xml makes the game verify auth-response signatures with the
production server's RSA public key (ctr_ps4.pub). A contributor running their own RyuNET
checkout has a DIFFERENT ctr_ps4.key there, so every auth reply fails verification and the
game retries for ever (200 code=700 in the server log, then silence).

This script rewrites the SAME patch into the player's data folder (patches/), whose file of
the same name replaces the bundled one (scripts/patches.py all_external_patches). It reads the
public modulus straight out of BB_AUTH_KEY (the local server's ctr_ps4.key, private or public
PEM) and keeps everything else from the bundled XML - address, edition, patch name - so the
selection logic and both editions (CUSA13795/CUSA14876) behave exactly as before.

Run from run.sh, gated on BB_AUTH_KEY. The repository's own patch file is never modified, so
playing on the production server keeps the production key.
"""
import argparse
import base64
import subprocess
import sys
from pathlib import Path
from xml.etree import ElementTree as ET

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'tools'))
from make_online_key_patch import extract_modulus  # noqa: E402

MARKER = 'generated by scripts/online_key_local.py'


def public_pem(key_path: Path) -> str:
    """The key's public half as PEM (a private PEM goes through openssl; a public one passes through)."""
    text = key_path.read_text(encoding='utf-8', errors='replace')
    if 'PUBLIC KEY' in text:
        return text
    out = subprocess.run(['openssl', 'rsa', '-in', str(key_path), '-pubout'],
                         capture_output=True, text=True)
    if out.returncode != 0 or 'BEGIN PUBLIC KEY' not in out.stdout:
        raise SystemExit(f'online_key_local: {key_path}: not a readable RSA key ({out.stderr.strip()})')
    return out.stdout


def local_xml(bundled: Path, key_path: Path) -> bytes:
    """The bundled Online patch with the Value line replaced by BB_AUTH_KEY's modulus."""
    modulus = extract_modulus_text(public_pem(key_path))
    tree = ET.parse(bundled)
    root = tree.getroot()
    lines = [line for meta in root.iter('Metadata') for line in meta.iter('Line')]
    if len(lines) != 1:
        raise SystemExit(f'online_key_local: {bundled.name}: expected one Line, found {len(lines)}')
    lines[0].set('Value', modulus.hex().upper())
    root.insert(0, ET.Comment(' ' + MARKER + ' (value: the LOCAL server\'s key; delete this file to go back to the bundled one) '))
    ET.indent(tree, space='    ')
    body = ET.tostring(root, encoding='unicode')
    return ('<?xml version="1.0" encoding="utf-8"?>\n' + body + '\n').encode()


def extract_modulus_text(pem: str) -> bytes:
    import tempfile
    with tempfile.NamedTemporaryFile('w', suffix='.pem', delete=False) as tmp:
        tmp.write(pem)
        path = Path(tmp.name)
    try:
        return extract_modulus(path)
    finally:
        path.unlink(missing_ok=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', required=True, type=Path, help='the game data folder (BB_DATA_DIR)')
    parser.add_argument('--key', required=True, type=Path, help='the LOCAL server\'s ctr_ps4.key (private or public PEM)')
    parser.add_argument('--bundled', type=Path, default=Path(__file__).resolve().parent.parent / 'patches',
                        help='the repo\'s patches/ folder')
    args = parser.parse_args()

    key_path = args.key.expanduser()
    if not key_path.is_file():
        raise SystemExit(f'online_key_local: BB_AUTH_KEY {key_path} does not exist')
    out_dir = args.data / 'patches'
    out_dir.mkdir(parents=True, exist_ok=True)

    written, skipped = [], []
    for bundled in sorted(args.bundled.glob('CrashTeamRacingOnline*.xml')):
        target = out_dir / bundled.name
        if target.is_file() and MARKER not in target.read_text(encoding='utf-8', errors='replace'):
            # The player's own file: never overwrite something we did not generate.
            skipped.append(target)
            continue
        target.write_bytes(local_xml(bundled, key_path))
        written.append(target.name)
    if skipped:
        raise SystemExit(
            'online_key_local: refusing to continue with a half-applied auth key — these data-folder '
            'patch file(s) are not ours: '
            + ', '.join(str(p) for p in skipped)
            + '. Delete them (or review them) so the local key can be written.')
    if not written:
        raise SystemExit('online_key_local: no CrashTeamRacingOnline*.xml in the bundled patches folder')
    print(f'Local auth key: the game now verifies auth signatures with {key_path} '
          f'({", ".join(written)} in {out_dir}); production play is unaffected (the bundled patch stays).')


if __name__ == '__main__':
    main()
