"""The overlay menu's texts (gpu/shim): the English keys of its translation tables and the tables
for French, Portuguese, German and Italian, generated from gpu/shim/menu_texts/*.json.

The Spanish table (gpu/shim/bbport_menu_es.cpp) is written by hand; its keys are the menu's English
texts. Each JSON file maps those keys to [French, Portuguese, German, Italian]; this writes
gpu/shim/bbport_menu_more.cpp. A key missing from the JSON files stays English in those languages.

Usage: python tools/menu_texts.py keys | write | check
SPDX-License-Identifier: GPL-2.0-or-later
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPANISH = ROOT / 'gpu/shim/bbport_menu_es.cpp'
SOURCES = ROOT / 'gpu/shim/menu_texts'
TARGET = ROOT / 'gpu/shim/bbport_menu_more.cpp'
LANGUAGES = ('French', 'Portuguese', 'German', 'Italian')
TOKEN = re.compile(r'"((?:[^"\\]|\\.)*)"|(//[^\n]*)|([{},])', re.S)
ESCAPES = {'n': '\n', 't': '\t', '"': '"', '\\': '\\', "'": "'"}
BACKSLASH = chr(92)


def unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == BACKSLASH and i + 1 < len(s):
            out.append(ESCAPES.get(s[i + 1], s[i + 1]))
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def spanish_pairs():
    text = SPANISH.read_text(encoding='utf-8')
    start = text.index('table = {') + len('table = {')
    body = text[start:text.index('};', start)]
    pairs, group, current, depth = [], [], None, 0
    for m in TOKEN.finditer(body):
        literal, comment, punct = m.groups()
        if comment:
            continue
        if literal is not None:
            current = (current or '') + unescape(literal)
        elif punct == '{':
            depth += 1
            group, current = [], None
        elif punct == ',':
            if depth and current is not None:
                group.append(current)
                current = None
        elif punct == '}':
            if current is not None:
                group.append(current)
            if len(group) == 2:
                pairs.append(tuple(group))
            depth -= 1
            current = None
    return pairs


def keys():
    seen, out = set(), []
    for english, _ in spanish_pairs():
        if english not in seen:
            seen.add(english)
            out.append(english)
    return out


def literal(s):
    out = []
    for ch in s:
        if ch == '"' or ch == BACKSLASH:
            out.append(BACKSLASH + ch)
        elif ch == '\n':
            out.append(BACKSLASH + 'n')
        elif ch == '\t':
            out.append(BACKSLASH + 't')
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def merged():
    table = {}
    for f in sorted(SOURCES.glob('*.json')):
        table.update(json.loads(f.read_text(encoding='utf-8')))
    return table


def generate():
    known = set(keys())
    table = merged()
    unknown = sorted(k for k in table if k not in known)
    if unknown:
        raise SystemExit('menu_texts: keys not in the Spanish table: ' + repr(unknown[:5]))
    bad = sorted(k for k, v in table.items() if not isinstance(v, list) or len(v) != len(LANGUAGES))
    if bad:
        raise SystemExit('menu_texts: entries without 4 translations: ' + repr(bad[:5]))
    lines = ['// Generated by tools/menu_texts.py from gpu/shim/menu_texts/*.json: do not edit.',
             '// The overlay menu in French, Portuguese, German and Italian (the Spanish one: bbport_menu_es.cpp).',
             '#include <string>', '#include <string_view>', '#include <unordered_map>', '',
             'namespace BbSettings {', '', 'namespace {',
             'struct More { const char* french; const char* portuguese; const char* german; const char* italian; };',
             'const std::unordered_map<std::string_view, More>& Table() {',
             '    static const std::unordered_map<std::string_view, More> table = {']
    for key in keys():
        if key in table:
            v = table[key]
            lines.append('    {' + literal(key) + ', {' + ', '.join(literal(x) for x in v) + '}},')
    lines += ['    };', '    return table;', '}', '} // namespace', '',
              '// language: 0 French, 1 Portuguese, 2 German, 3 Italian',
              'const char* MoreLanguages(const char* english, int language) {',
              '    const auto& table = Table();',
              '    const auto it = table.find(english);',
              '    if (it == table.end()) return english;',
              '    const More& m = it->second;',
              '    return language == 0 ? m.french : language == 1 ? m.portuguese : language == 2 ? m.german : m.italian;',
              '}', '', '} // namespace BbSettings', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    what = sys.argv[1] if len(sys.argv) > 1 else 'keys'
    if what == 'keys':
        for k in keys():
            print(json.dumps(k, ensure_ascii=False))
    elif what == 'missing':
        table = merged()
        for k in keys():
            if k not in table:
                print(json.dumps(k, ensure_ascii=False))
    elif what == 'write':
        TARGET.write_bytes(generate().encode('utf-8'))
        print(f'{TARGET.relative_to(ROOT)}: {len(merged())} of {len(keys())} texts')
    elif what == 'check':
        ok = TARGET.is_file() and TARGET.read_text(encoding='utf-8') == generate()
        print('menu_texts: ' + ('current' if ok else 'OUT OF DATE (python tools/menu_texts.py write)'))
        sys.exit(0 if ok else 1)
