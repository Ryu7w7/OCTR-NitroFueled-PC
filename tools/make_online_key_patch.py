"""Generate CrashTeamRacingOnline.xml from an RSA-2048 public key PEM.

Replaces the official Demonware RSA-2048 public key in the loaded image at runtime,
allowing custom private servers (like ryunet-demonware-ctr) to sign auth responses
without modifying the original eboot.bin on disk.
"""
import argparse
import base64
from pathlib import Path
import sys

EBOOT_BASE = 0x400000
IMAGE_KEY_OFFSET = 0x1becf98
IMAGE_MODULUS_OFFSET = IMAGE_KEY_OFFSET + 9  # 0x1becfa1
PATCH_ADDRESS = IMAGE_MODULUS_OFFSET + EBOOT_BASE  # 0x01fecfa1
EXPECTED_HEAD = bytes.fromhex('3082010a0282010100')
EXPECTED_TAIL = bytes.fromhex('0203010001')


def extract_modulus(pem_path):
    text = Path(pem_path).read_text(encoding='utf-8', errors='replace')
    lines = [l.strip() for l in text.splitlines() if not l.startswith('-----')]
    der = base64.b64decode(''.join(lines))

    # Look for integer marker of 256 bytes with leading 0x00: 02 82 01 01 00
    idx = der.find(bytes.fromhex('0282010100'))
    if idx == -1:
        raise ValueError("Could not find 2048-bit modulus marker (02 82 01 01 00) in public key DER")
    modulus = der[idx + 5 : idx + 5 + 256]
    if len(modulus) != 256:
        raise ValueError(f"Extracted modulus length is {len(modulus)}, expected 256 bytes")

    # Exponent check (should be 65537: 02 03 01 00 01)
    if not der.endswith(EXPECTED_TAIL):
        raise ValueError("Public exponent is not 65537 (02 03 01 00 01)")

    return modulus


def verify_game_image(game_dir):
    game_path = Path(game_dir)
    eboot_path = game_path / 'eboot.bin'
    if not eboot_path.is_file():
        raise FileNotFoundError(f"eboot.bin not found in {game_dir}")

    # Use prepare module if available
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'scripts'))
    import prepare
    elf, header, ph, _, _ = prepare.parse_self(eboot_path.read_bytes())
    loads = [p for p in ph if p['type'] in (1, 0x61000010)]
    img = bytearray(max(p['vaddr'] + p['memsz'] for p in loads))
    for p in loads:
        img[p['vaddr'] : p['vaddr'] + p['filesz']] = prepare.span(elf, p['offset'], p['filesz'])

    head = img[IMAGE_KEY_OFFSET : IMAGE_KEY_OFFSET + 9]
    tail = img[IMAGE_KEY_OFFSET + 265 : IMAGE_KEY_OFFSET + 270]

    if head != EXPECTED_HEAD or tail != EXPECTED_TAIL:
        raise ValueError(f"eboot.bin in {game_dir} does not match expected Demonware key pattern. Is it CUSA13795 v1.21?")
    print(f"Verified target key in {eboot_path} image at offset {hex(IMAGE_KEY_OFFSET)}.")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('pubkey', type=Path, help="Path to custom Demonware public key PEM")
    p.add_argument('--game', type=Path, default=None, help="Optional game folder to verify eboot.bin against")
    p.add_argument('--out', type=Path, default=Path('patches/CrashTeamRacingOnline.xml'), help="Output XML patch file")
    args = p.parse_args()

    if args.game:
        verify_game_image(args.game)

    modulus = extract_modulus(args.pubkey)
    modulus_hex = modulus.hex().upper()

    xml_content = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_online_key_patch.py from {args.pubkey.name} -->
<Patch>
    <TitleID>
        <ID>CUSA13795</ID>
    </TitleID>
    <Metadata Title="Crash Team Racing Nitro-Fueled"
              Name="Online: custom Demonware key"
              Note="Replaces official Demonware RSA-2048 public key with server custom key for auth response signature verification"
              Author="RyuNET / SacredFire"
              PatchVer="1.0"
              AppVer="01.21"
              AppElf="eboot.bin">
        <PatchList>
            <Line Type="bytes" Address="{hex(PATCH_ADDRESS)}" Value="{modulus_hex}"/>
        </PatchList>
    </Metadata>
</Patch>
'''

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(xml_content, encoding='utf-8')
    print(f"Written online key patch to {args.out} (Address: {hex(PATCH_ADDRESS)}, Length: {len(modulus)} bytes)")


if __name__ == '__main__':
    main()
